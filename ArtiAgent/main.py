# The Windows console defaults to GBK (cp936). Model output is full of Unicode
# math symbols (→ ✓ ≈ − ⌀ ² ³ …) that are outside GBK. Writing those as GBK bytes
# then re-decoding as UTF-8 (what the tool-capture layer and the session log do)
# produces U+FFFD mojibake; and a raw GBK console would raise UnicodeEncodeError.
# Reconfigure stdio to emit UTF-8 (matching the log + capture layer), replacing any
# still-unencodable character instead of crashing.
for _stream in (sys.stdout, sys.stderr):
    _reconfigure = getattr(_stream, "reconfigure", None)
    if _reconfigure is not None:
        _reconfigure(encoding="utf-8", errors="replace")


