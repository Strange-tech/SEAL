def _emit_result(path, asset_dir, center=None, dims=None, rpy=None):
	try:
		p = Path(path).expanduser().resolve()
		p.parent.mkdir(parents=True, exist_ok=True)
		payload = {
			"asset_dir": str(asset_dir),
			"center": [round(float(v), 6) for v in (center or (0.0, 0.0, 0.0))],
			"dims": [round(float(v), 6) for v in (dims or (0.0, 0.0, 0.0))],
			"rpy": [round(float(v), 6) for v in (rpy or (0.0, 0.0, 0.0))],
		}
		p.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
		print(f"[emit-result] wrote {p}", file=sys.stderr)
	except Exception as e:
		print(f"[emit-result] failed: {e}", file=sys.stderr)


def _parse_box(arg):
	# Parse --box '<cx,cy,cz>,<w,h,l>[,<rx,ry,rz>]' (rpy optional) or a JSON object.
	s = arg.strip()
	if s.startswith("{"):
		try:
			obj = json.loads(s)
		except json.JSONDecodeError as e:
			raise ValueError(f"--box JSON invalid: {e}")
		return _normalize_box(obj.get("center"), obj.get("dims"), obj.get("rpy", (0.0, 0.0, 0.0)))
	parts = [p.strip() for p in s.split(",")]
	if len(parts) < 6:
		raise ValueError("--box must be '<cx,cy,cz>,<w,h,l>[,<rx,ry,rz>]' or JSON {center,dims,rpy}")
	center = parts[0:3]
	dims = parts[3:6]
	rpy = parts[6:9] if len(parts) >= 9 else ("0", "0", "0")
	return _normalize_box(center, dims, rpy)


def _normalize_box(center, dims, rpy):
	try:
		center = [float(v) for v in center]
		dims = [float(v) for v in dims]
		rpy = [float(v) for v in rpy]
	except (TypeError, ValueError) as e:
		raise ValueError(f"--box values must be numbers: {e}")
	if len(center) != 3 or len(dims) != 3 or len(rpy) != 3:
		raise ValueError("--box center/dims/rpy must each have 3 numbers")
	if any(v <= 0 for v in dims):
		raise ValueError("--box dims must be positive")
	return {"center": center, "dims": dims, "rpy": rpy}


def _box_constraint_text(box):
	cx, cy, cz = box["center"]
	w, h, l = box["dims"]
	rx, ry, rz = box["rpy"]
	return chr(10).join([
		"<box_constraint>",
		f"Reference box from the layout (--box): target dims (w x h x l) = ({w} x {h} x {l}) centred at ({cx}, {cy}, {cz}), orientation rpy = ({rx}, {ry}, {rz}).",
		"This is a SOFT reference, not a hard fit. Author the object at its natural, believable size with its geometric centre at the world origin (0,0,0), in CadQuery z-up (the SDK auto-converts to the y-up world frame: front +z, up +y). Do NOT apply any position offset or rotation; do NOT call fit_to_box.",
		"The scene placement (translation to ({cx}, {cy}, {cz}) and rotation rpy) is applied separately by the renderer - the model only supplies the canonical geometry.",
		"After each compile, the harness reports the delta between this reference box and the object's actual box (position/scale/rotation). Analyze whether the actual box is acceptable; if not, adjust the model and recompile.",
		"</box_constraint>",
	])
def _emit_with_real_bbox(emit_result, record_dir, repo_root, box=None):
	real_dims = None
	try:
		center, dims = compute_model_real_bbox(Path("model.py"), asset_root=Path(".bbox_tmp"))
		real_dims = dims
	except Exception as e:
		print(f"[real-bbox] failed: {e}", file=sys.stderr)
	if real_dims is None:
		real_dims = box["dims"] if box else (0.0, 0.0, 0.0)
	placement_center = box["center"] if box else (0.0, 0.0, 0.0)
	placement_rpy = box["rpy"] if box else (0.0, 0.0, 0.0)
	_emit_result(emit_result, record_dir, center=placement_center, dims=real_dims, rpy=placement_rpy)


def main():
	if "-h" in sys.argv[1:] or "--help" in sys.argv[1:]:
		print_help()
		sys.exit(0)
	if len(sys.argv) < 2:
		print("Usage: python main.py --task 'your task'", file=sys.stderr)
		sys.exit(1)
	if len(sys.argv) == 3 and sys.argv[1] == "-restore":
		sys.exit(restore(sys.argv[2]))

	# -- parse flags (--provider, --model, --image, --structure, --max-rounds); remaining args are positional --
	provider_name = os.environ.get("PROVIDER", "deepseek")
	model_override = None
	image_path = None
	emit_result = None
	structure_mode = "auto"
	max_rounds = 100
	edit_record_id = None
	task = None
	lineage = None
	review_requested = False
	reason = "creation"
	box_arg = None
	positional = []
	i = 0
	raw_args = sys.argv[1:]
	while i < len(raw_args):
		a = raw_args[i]
		if a in ("--provider", "--model", "--image", "--emit-result", "--structure", "--max-rounds", "--edit", "--task", "--reason", "--box"):
			if i + 1 >= len(raw_args):
				print(f"Usage: {a} <value>", file=sys.stderr)
				sys.exit(1)
			if a == "--provider":
				provider_name = raw_args[i + 1]
			elif a == "--model":
				model_override = raw_args[i + 1]
			elif a == "--image":
				image_path = raw_args[i + 1]
			elif a == "--emit-result":
				emit_result = raw_args[i + 1]
			elif a == "--structure":
				structure_mode = raw_args[i + 1]
			elif a == "--edit":
				edit_record_id = raw_args[i + 1]
			elif a == "--task":
				task = raw_args[i + 1]
			elif a == "--reason":
				reason = raw_args[i + 1]
			elif a == "--box":
				box_arg = raw_args[i + 1]
			else:
				max_rounds = raw_args[i + 1]
			i += 2
			continue
		if a == "--review":
			review_requested = True
			i += 1
			continue
		if a.startswith("--provider="):
			provider_name = a.split("=", 1)[1]
		elif a.startswith("--model="):
			model_override = a.split("=", 1)[1]
		elif a.startswith("--image="):
			image_path = a.split("=", 1)[1]
		elif a.startswith("--emit-result="):
			emit_result = a.split("=", 1)[1]
		elif a.startswith("--structure="):
			structure_mode = a.split("=", 1)[1]
		elif a.startswith("--edit="):
			edit_record_id = a.split("=", 1)[1]
		elif a.startswith("--task="):
			task = a.split("=", 1)[1]
		elif a.startswith("--max-rounds="):
			max_rounds = a.split("=", 1)[1]
		elif a.startswith("--reason="):
			reason = a.split("=", 1)[1]
		elif a.startswith("--box="):
			box_arg = a.split("=", 1)[1]
		else:
			positional.append(a)
		i += 1

	structure_mode = structure_mode.strip().lower()
	if structure_mode not in ("always", "auto", "never"):
		print(f"Error: --structure must be one of always|auto|never, got {structure_mode!r}", file=sys.stderr)
		sys.exit(1)
	# --max-rounds accepts a positive integer (bounded) or 'unlimited'/'0' (no bound).
	_unlimited_tokens = {"unlimited", "none", "inf", "infinity", "0"}
	if isinstance(max_rounds, str) and max_rounds.strip().lower() in _unlimited_tokens:
		max_rounds = None
	else:
		try:
			max_rounds = int(max_rounds)
		except (TypeError, ValueError):
			print(f"Error: --max-rounds must be a positive integer or 'unlimited', got {max_rounds!r}", file=sys.stderr)
			sys.exit(1)
		if max_rounds <= 0:
			print(f"Error: --max-rounds must be a positive integer or 'unlimited', got {max_rounds}", file=sys.stderr)
			sys.exit(1)

	reason = reason.strip().lower()
	if reason not in ("creation", "fix_bugs"):
		print(f"Error: --reason must be one of creation|fix_bugs, got {reason!r}", file=sys.stderr)
		sys.exit(1)
	if reason == "fix_bugs" and not edit_record_id:
		print("Error: --reason fix_bugs requires --edit <record_id>", file=sys.stderr)
		sys.exit(1)
	box = None
	if box_arg:
		try:
			box = _parse_box(box_arg)
		except ValueError as e:
			print(f"Error: {e}", file=sys.stderr)
			sys.exit(1)
		print(f"[Box constraint: center={box['center']} dims={box['dims']} rpy={box['rpy']}]", file=sys.stderr)

	try:
		provider = get_provider(provider_name, model=model_override)
	except ValueError as e:
		print(e, file=sys.stderr)
		sys.exit(1)
	print(f"[Provider: {provider.name} |model={provider.model} |{provider.base_url}]", file=sys.stderr)

	# -- optional reference image: require provider vision support before proceeding --
	if image_path:
		if not provider.spec.supports_image_content:
			print(
				f"Error: provider {provider.name!r} does not support image input "
				f"(supports_image_content=False)",
				file=sys.stderr,
			)
			sys.exit(1)
		img_path = Path(image_path).expanduser().resolve()
		if not img_path.is_file():
			print(f"Error: image file not found: {img_path}", file=sys.stderr)
			sys.exit(1)
		image_path = str(img_path)
		print(f"[Image: {img_path}]", file=sys.stderr)
	
	repo_root = Path(__file__).resolve().parent
	_, designer_prompt = load_system_prompt_text("designer_system_prompt.txt", 
		provider="deepseek", sdk_package="sdk")
	sdk_docs = load_sdk_docs_reference(repo_root, sdk_package="sdk")
	skills = discover_skills()
	runtime_guidance = (
		"<runtime_task_guidance>\n"
		"- Read the current `model.py` before editing.\n"
		"- Author the object with its geometric centre at the world origin (0,0,0), in canonical y-up / +z-forward orientation (front +z, up +y). Do NOT apply any position offset or rotation; the scene placement is applied separately by the renderer.\n"
		"- SDK docs are read with `read_file` using the virtual paths in the preloaded quickstart "
		"index (e.g. docs/sdk/references/core-types.md, docs/sdk/references/articulated-object.md, "
        "docs/sdk/references/geometry/hinges.md).\n"
		"- Start with a realism-first structure plan. Use one coherent scaffold when the real object "
		"needs layered bodies, hollow forms, mechanisms, or repeated features; otherwise make small "
		"focused edits.\n"
		"- Write a complete, compilable `model.py` in your FIRST `write_file` call (build the whole "
		"articulated object, not a stub), then iterate with small `edit_file` changes.\n"
		"- Do NOT probe CadQuery or the SDK with one-off `bash python -c` commands. Author geometry directly "
		"in `model.py`; `compile_model` reports API and usage errors for you.\n"
		"- Treat visual realism as part of the deliverable: make the object read clearly as the "
		"requested thing, with believable proportions, silhouette, colors/materials, and major visible "
		"surface treatment.\n"
		"- Run `compile_model` to check your latest revision.\n"
		"- If compile is clean and the model already satisfies the realism/mechanism brief, conclude.\n"
		"</runtime_task_guidance>"
	)
	system_note = designer_prompt + "\n\n" + sdk_docs + "\n\n" + runtime_guidance
	if box:
		system_note += "\n\n" + _box_constraint_text(box)

	if skills:
		system_note += (
			"\n\n<skill_guidance>\n"
			"A list of reusable skills is under '# Available skill' near the end of this prompt. "
			"Before authoring geometry that uses a CadQuery/SDK API (e.g. text, fillet, shell, loft, sweep, boolean), "
			"load the matching skill with the `skill` tool first: skills capture correct API signatures that are "
			"costly to rediscover by trial and error.\n"
			"</skill_guidance>"
		)

	if edit_record_id:
		system_note += """
			<edit_guidance>
			This is an edit request for an existing Articraft asset. The parent model.py has already been staged as the editable starting file. Treat that staged code as the current asset source, preserve the parts that still satisfy the original object, and make the smallest coherent set of changes needed for the new user request. Do not assume prior conversation history is available; use the staged code and this edit prompt as the source of truth.
			</edit_guidance>"""

	tools = [ReadFileTool(), WriteFileTool(), EditFileTool(), BashTool(), CompileModelTool(box=box), ProbeModelTool(), RealBboxTool(), FindExamplesTool()]
	if skills:
		tools.append(SkillTool(skills))
	sub_agent = SubAgentTool(provider, list(tools), skills)
	tools.append(sub_agent)
	reg = Registry(*tools)
	system_note += compose_system_prompt(skills)

	resume_id = ""
	if positional:
		if positional[0] == "-c":
			if len(positional) < 2:
				print("Usage: python main.py -c <session_id> --task 'your task'", file=sys.stderr)
				sys.exit(1)
			resume_id = positional[1]
		else:
			print(f"Unexpected argument: {positional[0]}", file=sys.stderr)
			sys.exit(1)
	if not task or not task.strip():
		print("Usage: python main.py --task 'your task'  (--task is required)", file=sys.stderr)
		sys.exit(1)

	raw_prompt = task

	if resume_id:
		try:
			sess = load_session(resume_id)
		except (OSError, ValueError) as e:
			print(f"Error: Failed to restore session: {e}", file=sys.stderr)
			sys.exit(1)
		print(f"Resume session {sess.id}", file=sys.stderr)
	else:
		try:
			sess = new_session_file([{"role": "system", "content": system_note}])
		except OSError as e:
			print(f"Error: Failed to create session: {e}", file=sys.stderr)
			sys.exit(1)
		print(f"Create session {sess.id}", file=sys.stderr)

	window = effective_context_window(provider.model)
	pre_estimate = estimate_tokens(sess.history)
	print(f"[Window: {provider.model} ->{window} tokens (Estimate before first request: {pre_estimate} tokens)]", file=sys.stderr)
	if pre_estimate >= window * BUDGET_FRACTION:
		print(f"[!] Estimated restored history is approaching budget limit. Noting this before sending requests - the actual value will be known after the first round response.", file=sys.stderr)

	# -- structure terse prompts into a short design brief before the agent loop --
	should_expand = structure_mode == "always" or (
		structure_mode == "auto" and should_structure(task)
	)
	if should_expand:
		try:
			brief = structure_task(provider, task, image_path=image_path)
		except Exception as e:
			print(f"Warning: structuring failed, using original prompt: {e}", file=sys.stderr)
		else:
			if brief:
				task = f"{task}\n\n<design_brief>\n{brief}\n</design_brief>"
				print(f"[Structured brief added{' (image-grounded)' if image_path else ''}]", file=sys.stderr)
	if box:
		task = f"{task}\n\n{_box_constraint_text(box)}"

	if image_path:
		user_content = [
			{"type": "text", "text": task},
			{"type": "image_url", "image_url": {"url": image_path_to_data_url(image_path)}},
		]
	else:
		user_content = task
	sess.history.append({"role": "user", "content": user_content})
	sess.save()

	if edit_record_id:
		parent_text, lineage = fork_context(repo_root, edit_record_id)
		if parent_text is None:
			print(f"Error: record not found or has no active model.py: {edit_record_id}", file=sys.stderr)
